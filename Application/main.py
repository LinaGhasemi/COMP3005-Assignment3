import os
import psycopg

# Connect to the PostgreSQL Student Management System database
def connect_db():
     # Use environment variables for connection settings and password
    connection = psycopg.connect(
        host=os.getenv("DB_HOST", "localhost"),
        port=os.getenv("DB_PORT", "5432"),
        dbname="Student Management System",
        user=os.getenv("DB_USER", "postgres"),
        password=os.environ["DB_PASSWORD"]
    )

    return connection


# Retrieve and display all students from the database
def getAllStudents():
    # Establish a database connection and create a cursor
    with connect_db() as connection:
        with connection.cursor() as cursor:

            # Execute a SELECT query to retrieve students ordered by ID
            cursor.execute("SELECT * FROM students ORDER BY student_id;")

             # Fetch all rows returned by the query
            students = cursor.fetchall()

             # Display each student's information in the terminal
            for student in students:
                print(student)


# Add a new student to the database
def addStudent(first_name, last_name, email, enrollment_date):
    with connect_db() as connection:
        with connection.cursor() as cursor:

            # Execute an INSERT query using parameterized values
            # The student_id is automatically generated by PostgreSQL
            cursor.execute(
                """
                INSERT INTO students (first_name, last_name, email, enrollment_date)
                VALUES (%s, %s, %s, %s);
                """,
                (first_name, last_name, email, enrollment_date)
            )

     # Confirm that the student was successfully added
    print ("\nStudent added successfully!\n")


# Update the email address of an existing student with a specified student_id
def updateStudentEmail(student_id, new_email):
    with connect_db() as connection:
        with connection.cursor() as cursor:

            # Execute an UPDATE query to update the email of the student with the matching ID
            cursor.execute(
                """
                UPDATE students
                SET email = %s
                WHERE student_id = %s;
                """,
                (new_email, student_id)
            )

     # Display a confirmation message
    print("\nStudent email updated successfully!\n")



# Delete a student from the database using their student_id
def deleteStudent(student_id):
    with connect_db() as connection:
        with connection.cursor() as cursor:

            # Execute a DELETE query only with the student with the specified ID
            cursor.execute(
                """
                DELETE FROM students
                WHERE student_id = %s;
                """,
                (student_id,)
            )

             # Check how many records were deleted
            deleted_rows = cursor.rowcount

    # Display a message based on whether a student was found
    if deleted_rows > 0:
        print("\nStudent deleted successfully!\n")
    else:
        print("\nNo student found with that ID.\n")


# Display a menu to perform student database operations
def main():
    # Keep displaying the menu until the user chooses to exit
    while True:
        # Display the available database operations
        print("\n--- Student Management System ---")
        print("1. View all students")
        print("2. Add a student")
        print("3. Update student email")
        print("4. Delete a student")
        print("5. Exit")

        # Get the user's menu selection
        choice = input("\nEnter your choice: ")

        try:
            # Call the appropriate CRUD function based on the selection
            if choice == "1":
                print("\nAll Students:")
                getAllStudents()

            elif choice == "2":
                first_name = input("Enter first name: ")
                last_name = input("Enter last name: ")
                email = input("Enter email: ")
                enrollment_date = input("Enter enrollment date (YYYY-MM-DD): ")

                addStudent(first_name, last_name, email, enrollment_date)

            elif choice == "3":
                student_id = int(input("Enter student ID: "))
                new_email = input("Enter new email: ")

                updateStudentEmail(student_id, new_email)

            elif choice == "4":
                student_id = int(input("Enter student ID: "))

                deleteStudent(student_id)

            elif choice == "5":
                print("\nExiting Student Management System.")
                break

            else:
                print("\nInvalid choice. Please try again.\n")

        except ValueError:
            # Handle invalid numeric input
            print("\nInvalid input. Student ID must be a number.\n")

        except Exception as error:
            # Handle database errors and other unexpected exceptions
            print("\nAn error occurred:\n")
            print(error)


# Run the program
if __name__ == "__main__":
    main()
